#!/usr/bin/env python3
"""Course titles and subject names for the product page header, in every language.
Reads content/courses/<lang>/ and the app's UI strings; writes src/header-titles.js.
    python3 appstore/screenshots/tools/header_titles.py
"""
import glob, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LANGS = "fr en ar cs da de el es fi he hr hu it ja nb nl pl pt pt-PT ro ru sk sl sv tr".split()
COURSES = ["course_149_", "course_264_", "course_281_", "course_179_", "course_241_", "course_290_",
           "course_69_", "course_150_", "course_275_", "course_136_"]
SUBJECTS = {"Art": "subject.art.short", "History": "subject.histoire.short",
            "Science": "subject.sciences.short", "Mythology": "subject.mythologie.short"}
TABLE = {"fr": "french", "en": "english", "es": "spanish", "de": "german", "pt": "portuguese",
         "pt-PT": "portuguesePortugal", "it": "italian", "tr": "turkish", "pl": "polish", "ro": "romanian",
         "nl": "dutch", "el": "greek", "sv": "swedish", "hu": "hungarian", "cs": "czech", "da": "danish",
         "nb": "norwegian", "ru": "russian", "hr": "croatian", "sl": "slovenian", "sk": "slovak",
         "ar": "arabic", "he": "hebrew", "fi": "finnish", "ja": "japanese"}
SWIFT = (ROOT / "ios/Sophia/Utilities/AppLocalizable.swift").read_text(encoding="utf-8")

def ui(lang):
    """The app's own table for that language, from the Swift source."""
    start = SWIFT.index(f"private static let {TABLE[lang]}: [String: String] = [")
    end = SWIFT.find("private static let", start + 20)
    return dict(re.findall(r'"([^"\n]+)":\s*"((?:[^"\\\n]|\\.)*)"', SWIFT[start:end if end > 0 else None]))

out = {}
for lang in LANGS:
    strings = ui(lang)
    titles = []
    for prefix in COURSES:
        files = glob.glob(str(ROOT / "content" / "courses" / lang / (prefix + "*.json")))
        titles.append(json.load(open(files[0], encoding="utf-8"))["title"] if files else None)
    out[lang] = {"titles": titles, "subjects": {k: strings.get(v) for k, v in SUBJECTS.items()}}
    missing = [COURSES[i] for i, t in enumerate(titles) if not t] + [k for k, v in out[lang]["subjects"].items() if not v]
    if missing:
        print(lang, "missing:", missing)
(ROOT / "appstore/screenshots/src/header-titles.js").write_text(
    "// Generated by tools/header_titles.py; do not edit.\nconst HEADER_L10N = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print(len(out), "languages")
