def row(*values: str) -> dict[str, str]:
    if len(values) != len(LANGS):
        raise ValueError(f"expected {len(LANGS)} values, got {len(values)}: {values[0]!r}")
    return dict(zip(LANGS, values))


def build_overrides() -> dict[str, dict[str, str]]:
    by_key = TABLE
    out = {lang: {} for lang in LANGS}
    for key, mapping in by_key.items():
        for lang, val in mapping.items():
            out[lang][key] = val
    return out


