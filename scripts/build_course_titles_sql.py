#!/usr/bin/env python3
"""Generate the self-contained ranking query with course titles inlined.

The ranking returns a courseId. Supabase holds no titles -- they ship inside the
app -- so they have to travel with the query. A temporary table does not work
here: the Supabase SQL editor opens a new connection per run, so anything
created with `create temporary table` is gone by the next statement. The titles
go in as a `values` CTE instead, which makes the file one statement that runs
anywhere on its own.

Usage:
    python scripts/build_course_titles_sql.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COURSES_V2 = ROOT / "ios" / "Sophia" / "Resources" / "CoursesV2"
OUT = ROOT / "supabase" / "queries" / "top_courses_with_titles.sql"

HEADER = """\
-- The ten most-read courses, with their titles. Self-contained: paste and run.
--
-- Generated by scripts/build_course_titles_sql.py -- re-run it when the
-- catalogue changes. The titles are inlined because Supabase has none of its
-- own, and because the SQL editor opens a new connection per run, which a
-- temporary table does not survive.
--
-- Reads the same snapshot as top_courses.sql, with the same limits: signed-in
-- users only, distinct users rather than volume, and no history behind it.

with titles (course_id, title) as (
  values
"""

BODY = """\
),
read as (
  select key as course_id,
         count(*) as readers,
         count(*) filter (where (value ->> 'isCompleted')::boolean) as finishers,
         round(avg((value ->> 'lastLessonIndex')::int)::numeric, 2) as avg_last_lesson
  from user_progress up
  cross join lateral jsonb_each(up.progress::jsonb -> 'courseProgress')
  group by key
),
saved as (
  select course_id, count(*) as saves
  from user_progress up
  cross join lateral jsonb_array_elements_text(
    coalesce(up.progress::jsonb -> 'favoriteCourseIds', '[]'::jsonb)
  ) as course_id
  group by course_id
)
select
  coalesce(t.title, r.course_id) as course,
  r.readers,
  r.finishers,
  round(100.0 * r.finishers / nullif(r.readers, 0), 1) as completion_pct,
  r.avg_last_lesson,
  coalesce(s.saves, 0) as saves
from read r
left join saved s on s.course_id = r.course_id
left join titles t on t.course_id = r.course_id
order by r.readers desc, r.finishers desc
limit 10;
"""


def main() -> int:
    rows = []
    for path in sorted(COURSES_V2.glob("*.fr.json")):
        course_id = path.name[: -len(".fr.json")]
        title = (json.loads(path.read_text(encoding="utf-8")).get("title") or "").strip()
        if title:
            quoted = title.replace("'", "''")
            rows.append(f"    ('{course_id}', '{quoted}')")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + ",\n".join(rows) + "\n" + BODY, encoding="utf-8")
    print(f"{len(rows)} title(s) -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
