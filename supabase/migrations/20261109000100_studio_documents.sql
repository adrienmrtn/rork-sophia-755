# Écrire un cours Sophia

Un cours Sophia se lit en cinq minutes, sur un téléphone, souvent dans les transports. Il répond à une question précise et laisse le lecteur avec une idée claire en tête. Voilà comment on l'écrit.

## Le titre est une question

« Pourquoi des soldats ennemis ont-ils fêté Noël ensemble en 1914 ? » plutôt que « La trêve de Noël ». Une question donne envie d'ouvrir et dit ce que le cours va démontrer. Trois à cent soixante caractères, sans point d'exclamation.

## 500 à 900 mots, en deux à douze parties

L'introduction (la première partie) est gratuite pour tous les lecteurs : elle pose la question, plante le décor et promet la réponse. Chaque partie suivante porte une idée, en trois ou quatre paragraphes courts. La dernière partie se termine par un bloc **À retenir** : une ou deux phrases que le lecteur doit garder.

## Des phrases courtes, des faits concrets

Une idée par phrase. Des dates, des lieux, des noms, des chiffres. Pas de jargon sans explication, pas de tiret long (le « — »), pas de paragraphe de plus de six lignes. Le gras sert à deux ou trois points clés par partie, pas plus.

## Le glossaire

Marquez entre doubles crochets les termes qu'un lecteur curieux mais non spécialiste pourrait ne pas connaître : `[[sfumato]]`, `[[Ligue hanséatique]]`. Trois à huit termes par cours, chacun avec une explication de deux ou trois phrases. L'éditeur vous signale les termes marqués sans explication.

## Les blocs qui font respirer

- **Le savais-tu ?** : une anecdote vraie, surprenante, en trois phrases.
- **Frise** : deux à six dates clés quand la chronologie compte.
- **Citation** : courte, sourcée, avec l'auteur.
- **Image** : choisie dans Wikimedia Commons depuis l'éditeur, le crédit s'ajoute tout seul. Une image par partie au plus.

## Les sources

Au moins deux : un livre, un article, une archive. Format court : auteur, titre, éditeur, année, pages. Elles s'affichent à la fin du cours et rassurent le lecteur.

## Ce que Sophia fait ensuite

