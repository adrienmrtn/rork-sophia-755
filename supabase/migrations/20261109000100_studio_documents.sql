# Writing a Sophia course

A Sophia course is read in five minutes, on a phone, often on a commute. It answers one precise question and leaves the reader with one clear idea. Here is how to write it.

## The title is a question

"Why did enemy soldiers celebrate Christmas together in 1914?" rather than "The Christmas truce". A question makes people open the course and says what it will show. Three to one hundred and sixty characters, no exclamation mark.

## 500 to 900 words, in two to twelve sections

The introduction (the first section) is free for every reader: it asks the question, sets the scene and promises the answer. Each following section carries one idea, in three or four short paragraphs. The last section ends with a **Key takeaway** block: one or two sentences the reader should keep.

## Short sentences, concrete facts

One idea per sentence. Dates, places, names, numbers. No jargon without an explanation, no em dash ("—"), no paragraph longer than six lines. Bold is for two or three key points per section, no more.

## The glossary

Mark in double brackets the terms a curious but non-specialist reader might not know: `[[sfumato]]`, `[[Hanseatic League]]`. Three to eight terms per course, each with a two- or three-sentence explanation. The editor flags marked terms that have no explanation.

## Blocks that let the text breathe

- **Did you know?**: a true, surprising anecdote in three sentences.
- **Timeline**: two to six key dates when chronology matters.
- **Quote**: short, sourced, with its author.
- **Image**: picked from Wikimedia Commons inside the editor; the credit is added for you. One image per section at most.

## Sources

At least two: a book, an article, an archive. Short format: author, title, publisher, year, pages. They appear at the end of the course and reassure the reader.

## What Sophia does next

You write neither the quiz, nor the translations, nor the narration. After review, Sophia produces eight open-book questions, translates the course into the app's 29 other languages, records the audio and publishes. So avoid untranslatable wordplay and references a reader in Tokyo or Warsaw could not follow.

## Sensitive topics

Religion, borders, current politics, health: describe, date, attribute viewpoints, do not take sides. A Sophia course explains; it does not campaign.
